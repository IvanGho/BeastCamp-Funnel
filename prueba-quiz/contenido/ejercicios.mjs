/** Devuelve el diccionario de ejercicios para un perfil ('peleador' | 'peso'), solo con los ids pedidos. */
export function ejerciciosDe(funnel, usados) {
  const salida = {};
  for (const [id, nombre, muneco, como, cuidado, cuidadoPeso] of TABLA) {
    if (usados && !usados.has(id)) continue;
    salida[id] = {
      nombre,
      como: como.slice(),
      cuidado: funnel === 'peso' && cuidadoPeso ? cuidadoPeso : cuidado,
      muneco,
      video: '',
    };
  }
  return salida;
}

export const IDS_EJERCICIOS = TABLA.map((t) => t[0]);
